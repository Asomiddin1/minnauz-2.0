const dictionaries: Record<Lang, Dict> = { uz, ru, en }

const STORAGE_KEY = 'minna-lang'

const LangContext = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: Dict }>({
  lang: 'uz',
  setLang: () => {},
  t: uz,
})

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => {
    if (typeof window === 'undefined') return 'uz'
    const stored = window.localStorage.getItem(STORAGE_KEY) as Lang | null
    return stored && stored in dictionaries ? stored : 'uz'
  })

  useEffect(() => {
    window.localStorage.setItem(STORAGE_KEY, lang)
    document.documentElement.lang = lang
  }, [lang])

  return (
    <LangContext.Provider value={{ lang, setLang, t: dictionaries[lang] }}>
      {children}
    </LangContext.Provider>
  )
}

export const useLang = () => useContext(LangContext)
